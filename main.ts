// Token Radar, model radar-5: a Node 22 program, standard library only.
//
// It reads the sealed snapshot from /input/snapshot.json (or --input <file|dir>), scores every
// pre-token protocol with the fitted comps curve in lib/model.ts, writes the ranked board to
// /output/board.json, writes the dashboard's data beside the page as /output/data.js, copies this
// repository's dashboard/ to /output and rebuilds its screenshots/ there from their base64 text
// (the GitHub connector cannot carry the binary PNGs), and writes /output/dossier.json with the
// vendored make.fun library. The two runs the grader makes must write the same bytes, so nothing
// here reads the clock, the environment's randomness or the filesystem's order: every sort has a
// slug tiebreak, every list is built in a fixed order, and the dossier is canonical JSON.
//
// The dashboard is a static page, no framework and no network: dashboard/index.html, dashboard/app.css
// and dashboard/app.js read /output/data.js, which this program writes from the same board, so the
// page and board.json can never disagree. The farm plan each row carries is generated by the same
// function the page runs, from the same protocol record.
//
// Outside the grader's container, MAKEFUN_OUTPUT_DIR stands in for /output:
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { boardIssue, buildRadar, dataScript, parseSnapshot } from './lib/model.ts';
import { buildDossier } from './vendor/makefun-board.ts';

const here = fileURLToPath(new URL('.', import.meta.url));

/** The scorer's own caps: the text cap shapes the bytes, the rest refuse. */
const TEXT_MAX_BYTES = 65_536;
const SCREENSHOT_CAPS = { max: 4, max_bytes: 524_288 };
const IMAGE_NAME = /^[A-Za-z0-9_][A-Za-z0-9._-]{0,127}$/;

/** --name <value> out of the arguments, or the fallback. */
function flag(name: string, fallback: string): string {
  const at = process.argv.indexOf(`--${name}`);
  if (at >= 0 && at + 1 < process.argv.length) return process.argv[at + 1]!;
  const joined = process.argv.find((a) => a.startsWith(`--${name}=`));
  return joined === undefined ? fallback : joined.slice(name.length + 3);
}

/** Copy one directory's regular files into `to`, skipping names that start with a dot. */
function copyFiles(from: string, to: string): string[] {
  if (!existsSync(from)) return [];
  mkdirSync(to, { recursive: true });
  const copied: string[] = [];
  for (const name of readdirSync(from).sort()) {
    if (name.startsWith('.')) continue;
    const path = join(from, name);
    if (!statSync(path).isFile()) continue;
    copyFileSync(path, join(to, name));
    copied.push(name);
  }
  return copied;
}

/** Decode the base64 screenshots in `from` into `to`, stripping the .b64 suffix: the PNGs travel
 *  as text because the GitHub connector cannot carry binary files, and this program rebuilds
 *  them byte for byte, so the images the judge sees are the screenshots the agent took. */
function decodeScreenshots(from: string, to: string): string[] {
  if (!existsSync(from)) return [];
  mkdirSync(to, { recursive: true });
  const decoded: string[] = [];
  for (const name of readdirSync(from).sort()) {
    if (!name.endsWith('.b64')) continue;
    const outName = name.slice(0, -4);
    if (!IMAGE_NAME.test(outName)) fail(`screenshots/${name}: a name is letters, digits and . _ -, 1 to 128 characters`);
    const bytes = Buffer.from(readFileSync(join(from, name), 'utf8'), 'base64');
    if (bytes.length === 0 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') {
      fail(`screenshots/${name}: not a PNG after base64 decode`);
    }
    writeFileSync(join(to, outName), bytes);
    decoded.push(outName);
  }
  return decoded;
}

function fail(message: string): never {
  process.stderr.write(`token radar: ${message}\n`);
  process.exit(1);
}

function run(): void {
  const inputArg = flag('input', '/input');
  const inputFile = inputArg.endsWith('.json') ? inputArg : join(inputArg, 'snapshot.json');
  if (!existsSync(inputFile)) {
    fail(`no snapshot at ${inputFile}: pass --input <snapshot.json|directory> or mount the sealed /input`);
  }
  const out = flag('output', process.env.MAKEFUN_OUTPUT_DIR ?? '/output');

  const snapshot = parseSnapshot(readFileSync(inputFile, 'utf8'));
  const { board, radar } = buildRadar(snapshot);
  const issue = boardIssue(board, snapshot);
  if (issue !== null) fail(`the model wrote a board the gate refuses: ${issue}`);

  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'board.json'), `${JSON.stringify({ rows: board })}\n`);
  writeFileSync(join(out, 'data.js'), dataScript(radar));

  const dashFiles = copyFiles(join(here, 'dashboard'), join(out, 'dashboard'));
  if (dashFiles.length === 0) fail('dashboard/ is empty: the page is what the judge reads');
  const shots = decodeScreenshots(join(here, 'screenshots'), join(out, 'screenshots'));
  if (shots.length < 3) {
    fail(`screenshots/ holds ${shots.length} image${shots.length === 1 ? '' : 's'}: hand in 3, the board, a detail view and a filtered view`);
  }

  // The dossier is written last: the scorer rebuilds it from this /output and compares bytes.
  const dossier = buildDossier(out, { text_max_bytes: TEXT_MAX_BYTES, screenshots: SCREENSHOT_CAPS, dashboard: { max_files: 400, max_bytes: 4_194_304 } });
  writeFileSync(join(out, 'dossier.json'), dossier);

  // The judge reads the dashboard's source from the dossier's text, capped at TEXT_MAX_BYTES: if
  // the source grows past it, the judge reads a partial page. Report the sizes so a cut is visible.
  const dashBytes = dashFiles.reduce((n, f) => n + statSync(join(out, 'dashboard', f)).size, 0);
  if (dashBytes > 60_000) {
    process.stderr.write(`token radar: warning: dashboard source is ${dashBytes} bytes; the dossier text cap ${TEXT_MAX_BYTES} may cut it\n`);
  }

  const top = board.slice(0, 3).map((r) => `#${r.rank} ${r.slug} $${r.implied_value_usd.toLocaleString('en-US')}`).join(', ');
  process.stdout.write(
    `token radar: ${snapshot.protocols.length} protocols, ${snapshot.watchlist.length} on the watchlist, ${board.length} rows scored (${radar.early_size} early, ${radar.live_size} live set aside)\n` +
      `token radar: top of the board: ${top}\n` +
      `token radar: dashboard source ${dashBytes} bytes in ${dashFiles.length} files, dossier ${dossier.length} bytes\n` +
      `token radar: wrote ${join(out, 'board.json')}, ${join(out, 'data.js')}, ${join(out, 'dashboard')} (${dashFiles.length} files), ${join(out, 'screenshots')} (${shots.length} images) and ${join(out, 'dossier.json')}\n`,
  );
}

run();
